#!/usr/bin/env python3
"""Builds superops/synology-wazuh-install-superops.sh from synology-wazuh-install.sh.

The SuperOps edition is the same installer with four differences:
  1. Settings come from SuperOps runtime variables instead of flags.
  2. All output goes to stdout with timestamps, so it shows in the run log.
  3. Any warning makes the script exit 1, so SuperOps flags the run.
  4. The closing hint refers to the SynologyAction variable.

Run from the repo root:  python3 tools/build-superops.py
tests/run-tests.sh fails if the committed SuperOps script is out of date.
"""
import os, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(root, "synology-wazuh-install.sh"), encoding="utf-8").read()

def cut(text, start, end, replacement, include_end=True):
    i = text.index(start)
    j = text.index(end, i + len(start))
    if include_end:
        j += len(end)
    return text[:i] + replacement + text[j:]

HEADER = '''#!/usr/bin/env bash
# shellcheck disable=SC2154  # SuperOps runtime variables are injected at run time
# =============================================================================
#  synology-wazuh-install-superops.sh  (SuperOps RMM edition)
#  Receive Synology DSM syslog (sign-ins, auto-block, file activity) on a
#  self-hosted Wazuh manager: adds a syslog listener restricted to the NAS,
#  installs tested decoders and rules, and proves them with wazuh-logtest
#  before the manager is restarted.
#
#  Run ON the Wazuh manager as root.
#
#  Author : Farmhouse Networking - https://www.farmhousenetworking.com
#  License: MIT
#  Repo   : https://github.com/FarmhouseNetworking/Wazuh-Synology
# =============================================================================
#
#  SuperOps: add as a Linux "Bash" script, run as root against the Wazuh
#  manager asset, and fill in the runtime variables below. The script exits
#  0 on success and 1 on any failure or warning, so SuperOps flags problems.
#
#  GENERATED FILE. Edit synology-wazuh-install.sh and run
#  tools/build-superops.py; do not edit this file by hand.
# =============================================================================

set -uo pipefail
exec 2>&1
'''

CONFIG = '''# ------------------- SUPEROPS RUNTIME VARIABLES ------------------------------
# Create these as Runtime Variables on the SuperOps script (names must match).
#   SynologyNasIp         NAS address(es), comma-separated     REQUIRED for install
#   SynologyAction        install | status | uninstall         (optional, default install)
#   SynologyPort          514                                  (optional)
#   SynologyProtocol      tcp | udp                            (optional, default tcp)
#   SynologyRuleBase      127500                               (optional)
#   SynologyAddListener   yes | no                             (optional, default yes)
#   SynologyOpenFirewall  yes | no                             (optional, default yes)
#   SynologyRestart       yes | no                             (optional, default yes)
#   SynologyForce         yes | no                             (optional, default no)
set +u
NAS_IP="$SynologyNasIp"
ACTION="$SynologyAction"
SYSLOG_PORT="$SynologyPort"
SYSLOG_PROTO="$SynologyProtocol"
RULE_BASE="$SynologyRuleBase"
ADD_LISTENER="$SynologyAddListener"
OPEN_FIREWALL="$SynologyOpenFirewall"
RESTART="$SynologyRestart"
FORCE="$SynologyForce"
set -u
# Defaults for optional variables left blank in SuperOps
[[ "$NAS_IP" == \\$* ]] && NAS_IP=""
[[ -z "$ACTION"        || "$ACTION"        == \\$* ]] && ACTION="install"
[[ -z "$SYSLOG_PORT"   || "$SYSLOG_PORT"   == \\$* ]] && SYSLOG_PORT="514"
[[ -z "$SYSLOG_PROTO"  || "$SYSLOG_PROTO"  == \\$* ]] && SYSLOG_PROTO="tcp"
[[ -z "$RULE_BASE"     || "$RULE_BASE"     == \\$* ]] && RULE_BASE="127500"
[[ -z "$ADD_LISTENER"  || "$ADD_LISTENER"  == \\$* ]] && ADD_LISTENER="yes"
[[ -z "$OPEN_FIREWALL" || "$OPEN_FIREWALL" == \\$* ]] && OPEN_FIREWALL="yes"
[[ -z "$RESTART"       || "$RESTART"       == \\$* ]] && RESTART="yes"
[[ -z "$FORCE"         || "$FORCE"         == \\$* ]] && FORCE="no"
ACTION="${ACTION,,}"; SYSLOG_PROTO="${SYSLOG_PROTO,,}"; ADD_LISTENER="${ADD_LISTENER,,}"
OPEN_FIREWALL="${OPEN_FIREWALL,,}"; RESTART="${RESTART,,}"; FORCE="${FORCE,,}"
# -----------------------------------------------------------------------------
'''

OUTPUT = '''# ------------------------------- OUTPUT --------------------------------------
WARN_COUNT=0
info() { echo "[$(date '+%H:%M:%S')] $*"; }
ok()   { echo "[$(date '+%H:%M:%S')] OK    $*"; }
warn() { WARN_COUNT=$((WARN_COUNT + 1)); echo "[$(date '+%H:%M:%S')] WARN  $*"; }
die()  { echo "[$(date '+%H:%M:%S')] ERROR $*"; exit 1; }

'''

TAIL = '''
if [ "$WARN_COUNT" -gt 0 ]; then
  echo "[$(date '+%H:%M:%S')] Finished with $WARN_COUNT warning(s). Exiting 1 so SuperOps flags this run."
  exit 1
fi
exit 0
'''

out = cut(src, "#!/usr/bin/env bash", "set -uo pipefail\n", HEADER)
out = cut(out, "# ----------------------------- CONFIGURATION", "# -----------------------------------------------------------------------------\n", CONFIG)
out = cut(out, "# ------------------------------- OUTPUT", "usage() {", OUTPUT, include_end=False)

old_hint = ' 4. Click "Send test log", then run:  sudo $0 status\n'
assert out.count(old_hint) == 1
out = out.replace(old_hint, ' 4. Click "Send test log", then run this script again with SynologyAction = status\n')

# Messages that name command-line flags are reworded to name the runtime variables.
REWORD = [
    ('{ usage >&2; die "--nas-ip is required."; }',
     'die "The SynologyNasIp runtime variable is required."'),
    ('re-run with --force to install alongside them."',
     're-run with SynologyForce = yes to install alongside them."'),
    ('Pick another range with --rule-base."',
     'Pick another range with SynologyRuleBase."'),
    ('die "--rule-base must be between',
     'die "SynologyRuleBase must be between'),
    ('Edit that block and re-run with --no-listener, or choose another --port / --protocol."',
     'Edit that block and re-run with SynologyAddListener = no, or choose another SynologyPort / SynologyProtocol."'),
    ('info "Leaving ossec.conf alone (--no-listener)."',
     'info "Leaving ossec.conf alone (SynologyAddListener = no)."'),
    ('info "Skipped restart (--no-restart). Restart wazuh-manager to activate the listener and rules."',
     'info "Skipped restart (SynologyRestart = no). Restart wazuh-manager to activate the listener and rules."'),
    ('info "Skipped restart (--no-restart)."',
     'info "Skipped restart (SynologyRestart = no)."'),
]
for old, new in REWORD:
    assert out.count(old) == 1, old
    out = out.replace(old, new)

old_main = 'case "$ACTION" in\n  install)   do_install ;;'
assert out.count(old_main) == 1
out = out.replace(old_main, 'info "synology-wazuh-install v$SCRIPT_VERSION (SuperOps edition) - action: $ACTION"\n' + old_main)
out = out.rstrip("\n") + "\n" + TAIL

dest = os.path.join(root, "superops", "synology-wazuh-install-superops.sh")
if "--check" in sys.argv:
    cur = open(dest, encoding="utf-8").read() if os.path.exists(dest) else ""
    sys.exit(0 if cur == out else 1)
os.makedirs(os.path.dirname(dest), exist_ok=True)
with open(dest, "w", encoding="utf-8", newline="\n") as f:
    f.write(out)
print("wrote", os.path.relpath(dest, root))
