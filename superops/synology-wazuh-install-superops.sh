valid_ip() {
  local ip="${1%%/*}" mask="" o
  [[ "$1" == */* ]] && mask="${1##*/}"
  [[ "$ip" =~ ^([0-9]{1,3})\.([0-9]{1,3})\.([0-9]{1,3})\.([0-9]{1,3})$ ]] || return 1
  for o in "${BASH_REMATCH[@]:1}"; do [ "$o" -le 255 ] || return 1; done
  if [ -n "$mask" ]; then
    [[ "$mask" =~ ^[0-9]{1,2}$ ]] && [ "$mask" -le 32 ] || return 1
  fi
  return 0
}

